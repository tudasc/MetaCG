#include "cgcollector2/metadata/exported/FunctionSignatureMetadata.h"
#include "cgmerge2/interface/CGMerge2Plugin.h"

#include "metacg/Callgraph.h"
#include "metacg/LoggerUtil.h"
#include "metacg/MergePolicy.h"

#include <algorithm>
#include <sstream>
#include <string>

using namespace metacg;

namespace {

constexpr const char* functionSignatureKey = FunctionSignatureMetadata::key;

/**
 * @return The function signature attached to the node by cgcollector2, or nullptr if the node has none.
 */
const FunctionSignature* getFunctionSignature(const CgNode& node) {
  if (const auto* md = node.get<FunctionSignatureMetadata>()) {
    return &md->ownSignature;
  }
  return nullptr;
}

std::string toString(const FunctionSignature& signature) {
  std::ostringstream os;
  os << signature;
  return os.str();
}

}  // namespace

/**
 * This policy extends MergeByNameAndOrigin: nodes are matched only if their function name, their origin (including the
 * header/source exception) and their function signature are identical.
 *
 * The function signature is taken from the 'FunctionSignatureMetadata' attached to a node (emitted by cgcollector2).
 * This distinguishes e.g. template instantiations with translation-unit-local types that share both mangled name and
 * origin. If the source node or a candidate node carries no signature metadata, the candidate is matched by name and
 * origin only, i.e. the policy behaves identically to MergeByNameAndOrigin, and a (unique) warning is emitted.
 *
 * The metadata library (libcgcollector2-metadata.so) is a dependency of this plugin, so the signature metadata is
 * registered as soon as CGMerge2 loads the plugin; no LD_PRELOAD is necessary.
 */
struct MergeByNameAndOriginAndSignature final : cgmerge2::Plugin {
  std::optional<MergeAction> findMatchingNode(const Callgraph& targetCG, const CgNode& sourceNode) const final {
    auto signatureMatches = findOriginMatches(targetCG, sourceNode);

    // Among the nodes with matching name and origin, filter out those with a different function signature.
    // If the source node or a candidate has no signature, the candidate is kept, i.e. matched by name and origin only.
    const auto* sourceSignature = getFunctionSignature(sourceNode);
    const auto differentSignature = [&](const CgNode* candidate) {
      const auto* candidateSignature = getFunctionSignature(*candidate);
      if (!sourceSignature || !candidateSignature) {
        MCGLogger::logWarnUnique(
            "Found nodes without {} while merging by name, origin and signature. These nodes are matched by name and "
            "origin only. Make sure the call graphs contain signature metadata (generated by cgcollector2 without "
            "--whole-program).",
            functionSignatureKey);
        MCGLogger::logDebug("Missing {} for '{}' (origin '{}') in the {} graph.", functionSignatureKey,
                            sourceNode.getFunctionName(), sourceNode.getOrigin().value_or("<none>"),
                            sourceSignature ? "target" : "source");
        return false;
      }
      if (!(*sourceSignature == *candidateSignature)) {
        MCGLogger::logDebug("Not merging '{}' (origin '{}') with node from origin '{}': signatures differ ({} vs. {})",
                            sourceNode.getFunctionName(), sourceNode.getOrigin().value_or("<none>"),
                            candidate->getOrigin().value_or("<none>"), toString(*sourceSignature),
                            toString(*candidateSignature));
        return true;
      }
      return false;
    };
    signatureMatches.erase(std::remove_if(signatureMatches.begin(), signatureMatches.end(), differentSignature),
                           signatureMatches.end());

    if (signatureMatches.empty()) {
      // There is no node with matching name, origin and signature: simply copy the source node into the target graph
      return {};
    }

    const auto* targetNode = signatureMatches.front();
    if (signatureMatches.size() > 1) {
      MCGLogger::logWarn(
          "Found multiple nodes matching name '{}', origin '{}' and signature! Merging with the first node ('{}').",
          sourceNode.getFunctionName(), sourceNode.getOrigin().value_or("<none>"),
          targetNode->getOrigin().value_or("<none>"));
    }

    // If the source node has no body (i.e. no definition) OR the target node has one, keep the target node.
    // If both functions have bodies: assume inline with identical function bodies.
    if (targetNode->getHasBody() || !sourceNode.getHasBody()) {
      return MergeAction(targetNode->getId(), false);
    }

    return MergeAction(targetNode->getId(), true);
  }

  std::string getPluginName() const final { return "MergeByNameAndOriginAndSignature"; }
};

extern "C" {
cgmerge2::Plugin* getCGMerge2Plugin() { return new MergeByNameAndOriginAndSignature(); }
}
